"""Fail-closed decision gate for a proposed Crashlytics code repair.

The caller supplies observed Crashlytics data and independently captured test
exit codes. A model's confidence or claim that tests passed is never a gate.
"""

from dataclasses import dataclass
from pathlib import PurePosixPath


SHELL_CRASH_TYPES = {'CrashedByAdbException'}


@dataclass(frozen=True)
class Decision:
    action: str
    reasons: tuple[str, ...]


def safe_path(value):
    if not isinstance(value, str) or not value or '\\' in value:
        return False
    path = PurePosixPath(value)
    return not path.is_absolute() and all(part not in ('.', '..') for part in value.split('/'))


def assess(crash, proposal=None, verification=None):
    """Return ``draft_pr`` only when source, change and observed tests align.

    ``crash`` must come from a trusted Crashlytics issue/event fetch, not from
    an email or a model's free-form response. ``verification`` is generated by
    the local runner after executing tests against the target checkout.
    """
    reasons = []
    if not isinstance(crash, dict) or not crash.get('event_id'):
        reasons.append('No verified Crashlytics sample event')
        crash = {}
    if crash.get('exception_type') in SHELL_CRASH_TYPES or crash.get('shell_injected') is True:
        reasons.append('Shell-induced test crash has no app code fix')
    frames = crash.get('app_frames') or []
    if not isinstance(frames, list) or not frames or not all(safe_path(path) for path in frames):
        reasons.append('No verified app-owned stack frame')
        frames = []
    if not isinstance(proposal, dict):
        reasons.append('No code repair proposal')
        proposal = {}
    root = proposal.get('root_cause_file')
    if root not in frames:
        reasons.append('Proposed root cause is not tied to an app stack frame')
    changed = proposal.get('changed_files') or []
    if not isinstance(changed, list) or not changed or not all(safe_path(path) for path in changed):
        reasons.append('No safe, relevant source change')
        changed = []
    if root not in changed:
        reasons.append('Proposed change does not touch the implicated app code')
    if proposal.get('app_fault') is not True or not proposal.get('causal_explanation'):
        reasons.append('App-owned cause and change relationship are unproven')
    if not isinstance(verification, dict):
        verification = {}
    if verification.get('regression_before_exit') in (None, 0):
        reasons.append('No observed failing regression before the fix')
    if verification.get('regression_after_exit') != 0:
        reasons.append('Regression did not pass after the fix')
    if verification.get('project_check_exit') != 0:
        reasons.append('Actual project check did not pass')
    if verification.get('tested_head') != proposal.get('head_sha') or not verification.get('tested_head'):
        reasons.append('Tests were not tied to the proposed commit')
    return Decision('issue_only' if reasons else 'draft_pr', tuple(reasons))
